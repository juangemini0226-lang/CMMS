def build_database_config() -> dict:
    # A) If URL exists, use dj_database_url (works for mysql://, postgres://)
    if DATABASE_URL:
        cfg = dj_database_url.parse(
            DATABASE_URL,
            conn_max_age=600,
            ssl_require=False,
        )
        # Ensure charset for MySQL
        if "mysql" in cfg.get("ENGINE", ""):
            cfg.setdefault("OPTIONS", {})
            cfg["OPTIONS"].setdefault("charset", "utf8mb4")
        return cfg

    # B) Railway MySQL variables (if no URL was provided)
    # Railway often provides MYSQLHOST/MYSQLUSER/etc.
    if IS_RAILWAY and os.getenv("MYSQLHOST"):
        return {
            "ENGINE": "django.db.backends.mysql",
            "NAME": os.getenv("MYSQLDATABASE", ""),
            "USER": os.getenv("MYSQLUSER", ""),
            "PASSWORD": os.getenv("MYSQLPASSWORD", ""),
            "HOST": os.getenv("MYSQLHOST", "mysql.railway.internal"),
            "PORT": os.getenv("MYSQLPORT", "3306"),
            "OPTIONS": {"charset": "utf8mb4"},
        }

    # C) Local fallback
    cfg = {
        "ENGINE": DB_ENGINE,
        "NAME": DB_NAME,
        "USER": DB_USER,
        "PASSWORD": DB_PASSWORD,
        "HOST": DB_HOST,
        "PORT": DB_PORT,
    }
    if "mysql" in cfg.get("ENGINE", ""):
        cfg.setdefault("OPTIONS", {})
        cfg["OPTIONS"].setdefault("charset", "utf8mb4")
    return cfg


