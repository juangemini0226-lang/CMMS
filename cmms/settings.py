def normalize_origin(value: str) -> str | None:
    cleaned = value.strip()
    if not cleaned:
        return None

    if cleaned.startswith(("http://", "https://")):
        return cleaned

    if cleaned.startswith("."):
        cleaned = f"*.{cleaned.lstrip('.') }"

    return f"https://{cleaned}"


