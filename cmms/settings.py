def build_allowed_hosts() -> list[str]:
    """
    Allowed hosts:
    - Local dev
    - Railway default domain (*.up.railway.app)
    - Any explicit ALLOWED_HOSTS env var
    - Railway public domain env vars (if present)
    """
    defaults = ["localhost", "127.0.0.1", "[::1]", ".up.railway.app"]

    env_hosts = [
        host.strip()
        for host in os.getenv("ALLOWED_HOSTS", "").split(",")
        if host.strip()
    ]

    railway_domain = (
        os.getenv("RAILWAY_PUBLIC_DOMAIN")
        or os.getenv("RAILWAY_STATIC_URL")
        or os.getenv("RAILWAY_URL")
    )

    hosts = defaults + ([railway_domain] if railway_domain else []) + env_hosts

    normalized: list[str] = []
    for host in hosts:
        if not host:
            continue
        cleaned = host.strip()
        if cleaned.startswith(("http://", "https://")):
            cleaned = urlparse(cleaned).netloc
        if cleaned and cleaned not in normalized:
            normalized.append(cleaned)

    return normalized


